/**
 * The generated entry point that `bun build --compile` bundles for release binaries: the CLI plus,
 * when the dashboard package exists, a static import of it (so its built SPA is embedded).
 */
import { mkdir } from 'node:fs/promises'
import { dirname, join, sep } from 'node:path'

/** A forward-slash absolute path as a JS string literal (Bun accepts `C:/…` on Windows). */
const specifier = (path: string): string => JSON.stringify(path.split(sep).join('/'))

/** Same exit handling as src/bin.ts. */
export const EXIT_GRACE_MS = 1000

export interface EntryInput {
  /** Absolute path of scripts/release/runtime.ts. */
  readonly runtime: string
  /** Absolute path of the dashboard's index module, or undefined to build without it. */
  readonly dashboard?: string
}

export function renderEntry(input: EntryInput): string {
  const lines = [
    '// Generated by packages/cli/scripts/release.ts for `bun build --compile`. Do not edit.',
    `import { runRelease } from ${specifier(input.runtime)}`,
    ...(input.dashboard === undefined ? [] : [`import * as dashboard from ${specifier(input.dashboard)}`]),
    '',
    `const code = await runRelease(process.argv.slice(2)${input.dashboard === undefined ? '' : ', dashboard'})`,
    'if (code !== undefined) {',
    '  process.exitCode = code',
    `  setTimeout(() => process.exit(code), ${EXIT_GRACE_MS}).unref()`,
    '}',
    '',
  ]
  return lines.join('\n')
}

/** Writes the entry to `<dir>/entry.ts` and returns its path. */
export async function writeEntry(dir: string, input: EntryInput): Promise<string> {
  const path = join(dir, 'entry.ts')
  await mkdir(dirname(path), { recursive: true })
  await Bun.write(path, renderEntry(input))
  return path
}
